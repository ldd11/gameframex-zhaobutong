public sealed class DifferenceSdkIosBuild : IPreprocessBuildWithReport
{
    public const string MinimumIosVersion = "15.0"; // Facebook 6.22 and DT Exchange 8.4.10 require iOS 15.
    const string PodfileHeader = "# Generated by DifferenceSdkIosBuild.\n";
    const string FirebasePlist = "GoogleService-Info.plist";
    const string MaxPlist = "AppLovin-Settings.plist";
    const string SkAdNetworkFile = "SdkDependencies/iOS/SKAdNetworkIds.txt";
    const string CrashlyticsScript = "\"${PODS_ROOT}/FirebaseCrashlytics/run\"";
    public int callbackOrder => -900;

